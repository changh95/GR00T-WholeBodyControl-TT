"""Slicing-by-8 tables of the zlib CRC-32 for the X280 monitor: writes x280/fw/crc32_tab.h (monitor.c mon_crc32).

    python3 $RT/x280/tools/gen_crc32_tab.py            # (re)write x280/fw/crc32_tab.h
    python3 $RT/x280/tools/gen_crc32_tab.py --check    # exit 1 if the checked-in header differs from this output

Table k, entry i is the CRC register after byte i followed by k zero bytes, starting from 0 and without zlib's
final inversion: the reflected 0xEDB88320 shift register advanced 8 (k + 1) bits from i. The tables are built
from that definition and, before anything is written, every entry is checked against zlib itself:
T[k][i] == zlib.crc32(bytes([i]) + bytes(k), 0xFFFFFFFF) ^ 0xFFFFFFFF. Stdlib only.

Why slicing-by-8 (and not a byte-wise table or slicing-by-4): LIM is not data-cacheable (Caches.md:26-31), so every
table entry the monitor reads is an uncached load. On silicon (S2 E2m, lim_bench) a dependent uncached load costs
28 cycles (pointer chase) and independent ones issued back to back about 7.8 cycles each (SELFTEST: 8 x 8 B per
line, 62 cycles per line). A byte-wise table is one dependent load per byte (>= 28 cycles/B). Slicing-by-4 issues
4 independent loads per 4 B but each round still waits for the previous one: ~28 + 3 x 7.8 + ALU, ~14 cycles/B.
Slicing-by-8 issues 8 per 8 B, and the 4 loads of the high word do not depend on the CRC chain at all:
~28 + 7 x 7.8 + ALU, ~11 cycles/B, against ~57 instructions/B (~60+ cycles/B) for the bitwise loop. 8 KiB of
.rodata keeps the image well under 48 KiB; slicing-by-16 would add 8 KiB more for ~2 cycles/B.
"""
from __future__ import annotations

import argparse
import sys
import zlib
from pathlib import Path

POLY = 0xEDB88320
SLICES = 8
OUT = Path(__file__).resolve().parents[1] / "fw" / "crc32_tab.h"


def tables(slices: int = SLICES) -> list[list[int]]:
    t0 = []
    for i in range(256):
        c = i
        for _ in range(8):
            c = (c >> 1) ^ (POLY if c & 1 else 0)
        t0.append(c)
    out = [t0]
    for _ in range(1, slices):
        out.append([(p >> 8) ^ t0[p & 0xFF] for p in out[-1]])
    return out


def reference(k: int, i: int) -> int:
    """The same entry from zlib alone (independent of tables())."""
    return zlib.crc32(bytes([i]) + bytes(k), 0xFFFFFFFF) ^ 0xFFFFFFFF


def check_against_zlib(t: list[list[int]]) -> None:
    bad = [(k, i) for k in range(len(t)) for i in range(256) if t[k][i] != reference(k, i)]
    if bad:
        raise SystemExit(f"gen_crc32_tab: {len(bad)} entries differ from zlib, first {bad[:4]}")


def render(t: list[list[int]]) -> str:
    lines = [
        "/* Generated by x280/tools/gen_crc32_tab.py: do not edit (tests/x280/test_crc32.py regenerates and compares).",
        " *",
        " * zlib CRC-32 (reflected polynomial 0xEDB88320) slicing-by-8 tables for monitor.c mon_crc32, 8 x 256 x 4 B =",
        " * 8 KiB of .rodata. mon_crc32_tab[k][i] = the CRC register after byte i followed by k zero bytes, from 0 and",
        " * without the final inversion: zlib.crc32(bytes([i]) + bytes(k), 0xFFFFFFFF) ^ 0xFFFFFFFF (checked against",
        " * zlib by the generator, by tests/x280/test_crc32.py and, in the linked image, by scripts/check_image.py).",
        " * Included by monitor.c only (it defines the table).",
        " */",
        "#ifndef X280_CRC32_TAB_H",
        "#define X280_CRC32_TAB_H",
        "",
        "#include <stdint.h>",
        "",
        f"const uint32_t mon_crc32_tab[{len(t)}][256] __attribute__((aligned(64))) = {{",
    ]
    for k, row in enumerate(t):
        lines.append(f"    {{   /* k = {k} */")
        for j in range(0, 256, 8):
            lines.append("        " + ", ".join(f"0x{v:08x}u" for v in row[j:j + 8]) + ",")
        lines.append("    },")
    lines += ["};", "", "#endif /* X280_CRC32_TAB_H */", ""]
    return "\n".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--out", type=Path, default=OUT)
    ap.add_argument("--check", action="store_true", help="compare with --out instead of writing it")
    args = ap.parse_args(argv)
    t = tables()
    check_against_zlib(t)
    text = render(t)
    if args.check:
        same = args.out.exists() and args.out.read_text() == text
        print(f"{args.out}: {'up to date' if same else 'DIFFERS from the generator'}")
        return 0 if same else 1
    args.out.write_text(text)
    print(f"wrote {args.out} ({len(t)} x 256 entries, checked against zlib)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
